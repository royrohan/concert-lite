    String sendScript() {
        StringBuilder usage = new StringBuilder();
        if (eco.hasMachines()) {
            usage.append("#   ./showcases/%1$s/send <smType> <eventType> <instanceKey> [payload.json | - | '{json}']\n"
                    + "#     (no payload: samples/<smType>/<eventType>.json)\n");
        }
        if (eco.hasEvents()) {
            usage.append("#   ./showcases/%1$s/send <EventType> [payload.json | - | '{json}'] [--at +5m | 2026-01-15T10:00:00Z] [--id ID]\n"
                    + "#     (no payload: samples/events/<EventType>.json; --at: SCHEDULED until then)\n");
        }
        return ("""
                #!/usr/bin/env bash
                # GENERATED by ./generate-concert-ecosystem -- regenerated on every run.
                # Send one %1$s event to Kinesis (concert-events), lock keys rendered from the payload:
                """ + usage + """
                # ./showcases/%1$s/send list shows the event types.
                set -euo pipefail
                here=$(cd "$(dirname "$0")" && pwd)
                if [ "${1:-}" = "list" ]; then
                  exec "$here/../../scripts/ecosystem-events.sh" %1$s list
                fi
                exec "$here/../../scripts/ecosystem-events.sh" %1$s send "$@"
                """).formatted(eco.name());
    }

    String sendFlowScript() {
        String dirs = (eco.hasMachines() ? "\"$here\"/samples/flows/*.json " : "") + (eco.hasEvents() ? "\"$here\"/samples/event-flows/*.json" : "");
        return """
                #!/usr/bin/env bash
                # GENERATED by ./generate-concert-ecosystem -- regenerated on every run.
                # Send the events of a flow file in order (default 500 ms apart):
                #   ./showcases/%1$s/send-flow <flow.json> [--delay-ms N]
                #   ./showcases/%1$s/send-flow all        (every flow under samples/)
                set -euo pipefail
                here=$(cd "$(dirname "$0")" && pwd)
                if [ "${1:-}" = "all" ]; then
                  shift
                  for f in %2$s; do
                    [ -f "$f" ] || continue
                    "$here/../../scripts/ecosystem-events.sh" %1$s flow "$f" "$@"
                  done
                  exit 0
                fi
                exec "$here/../../scripts/ecosystem-events.sh" %1$s flow "$@"
                """.formatted(eco.name(), dirs.strip());
    }

