    // ---- Deephaven ----

    /** Deephaven columns of a root: to-one primitives and enums, and those of to-one value classes one level down. */
    List<String[]> deephavenColumns(MachineDecl m) {
        return deephavenColumns(m.root());
    }

    /** Deephaven columns of a class (a machine's root or a keyed-state class). */
    List<String[]> deephavenColumns(ClassDef root) {
        List<String[]> out = new ArrayList<>();
        for (PropertyDef p : model.allProperties(root)) {
            if (!p.multiplicity().isToOne()) {
                continue;
            }
            if (model.isClass(p.type())) {
                ClassDef value = model.findClass(p.type().name()).orElseThrow();
                for (PropertyDef q : model.allProperties(value)) {
                    String kind = kind(q);
                    if (q.multiplicity().isToOne() && kind != null) {
                        out.add(new String[] {column(Ecosystem.pascal(p.name()) + Ecosystem.pascal(q.name())),
                                "/model/" + p.name() + "/" + q.name(), kind});
                    }
                }
                continue;
            }
            String kind = kind(p);
            if (kind != null) {
                out.add(new String[] {column(Ecosystem.pascal(p.name())), "/model/" + p.name(), kind});
            }
        }
        return out;
    }

    private static String column(String name) {
        return DH_SYSTEM.contains(name) ? "Model" + name : name;
    }

    private String kind(PropertyDef p) {
        if (model.isEnum(p.type())) {
            return "string";
        }
        if (!p.type().primitive()) {
            return null;
        }
        PrimitiveType t = p.type().primitiveType();
        return switch (t) {
            case STRING, STRICT_DATE, DATE -> "string";
            case INTEGER -> "long";
            case FLOAT, DECIMAL, NUMBER -> "double";
            case BOOLEAN -> "bool";
            case DATE_TIME -> "instant";
        };
    }

    String deephavenTable(MachineDecl m) {
        return py(eco.name()) + "_" + Ecosystem.rootTable(m.smType()) + "_latest";
    }

    private static String py(String s) {
        return s.replace('-', '_');
    }

    String deephaven() {
        String p = py(eco.name());
        StringBuilder sb = new StringBuilder();
        sb.append("# GENERATED by ./generate-concert-ecosystem -- do not edit: regenerated on every run.\n");
        sb.append("# Ecosystem \"").append(eco.name()).append("\" (from entity-snapshots):");
        if (eco.hasMachines()) {
            sb.append(" latest completed entity per root, completions per minute and state\n# distribution.");
        }
        if (eco.hasEvents()) {
            sb.append(" Event style: latest lifecycle row per event (by status, error queue, scheduled,\n"
                    + "# causation depth) and the latest document per keyed state.");
        }
        sb.append("\n# Loaded by concert.py, which exec()s every file in app.d/ecosystems with its\n");
        sb.append("# globals (consume, parse_instants, TYPES, agg, kc, dht) and exports the tables named in ECOSYSTEM_FIELDS.\n");
        sb.append("from deephaven import merge\n\n\n");
        sb.append("def _").append(p).append("_root(sm_type, columns):\n");
        sb.append("""
                    cols = {"EntityId": dht.string, "SmType": dht.string, "State": dht.string, "Version": dht.int64,
                            "CreatedAtText": dht.string, "CompletedAtText": dht.string}
                    mapping = {"entityId": "EntityId", "smType": "SmType", "state": "State", "version": "Version",
                               "createdAt": "CreatedAtText", "completedAt": "CompletedAtText"}
                    instants = ["CreatedAt", "CompletedAt"]
                    for column, pointer, kind in columns:
                        if kind == "instant":
                            instants.append(column)
                            column, kind = column + "Text", "string"
                        cols[column] = TYPES[kind]
                        mapping[pointer] = column
                    raw = consume("entity-snapshots", cols, mapping, kc.TableType.append()).where(f"SmType == `{sm_type}`")
                    latest = raw.agg_by(agg.sorted_last("Version", [c for c in raw.column_names if c != "EntityId"]), by=["EntityId"])
                    return parse_instants(latest, instants).update(
                        "LatencyMs = (isNull(CreatedAt) || isNull(CompletedAt)) ? NULL_LONG : diffMillis(CreatedAt, CompletedAt)")


                """);
        List<String> tables = new ArrayList<>();
        for (MachineDecl m : eco.machines()) {
            String t = deephavenTable(m);
            tables.add(t);
            sb.append(t).append(" = _").append(p).append("_root(\"").append(m.smType()).append("\", [\n");
            for (String[] c : deephavenColumns(m)) {
                sb.append("    (\"").append(c[0]).append("\", \"").append(c[1]).append("\", \"").append(c[2]).append("\"),\n");
            }
            sb.append("])\n");
        }
        List<String> fields = new ArrayList<>(tables);
        if (eco.hasMachines()) {
            String common = "[\"EntityId\", \"SmType\", \"State\", \"Version\", \"CreatedAt\", \"CompletedAt\", \"LatencyMs\"]";
            sb.append("\n").append(p).append("_latest = merge([").append(String.join(", ", tables.stream().map(t -> t + ".view(" + common + ")").toList()))
                    .append("])\n");
            sb.append(p).append("_state_distribution = ").append(p).append("_latest.count_by(\"Entities\", by=[\"SmType\", \"State\"]).sort([\"SmType\", \"State\"])\n");
            sb.append(p).append("_completions_per_minute = ").append(p).append("_latest.where(\"!isNull(CompletedAt)\") \\\n")
                    .append("    .update(\"Minute = lowerBin(CompletedAt, MINUTE)\") \\\n")
                    .append("    .count_by(\"Completions\", by=[\"Minute\", \"SmType\"]).sort_descending([\"Minute\"])\n");
            fields.addAll(List.of(p + "_latest", p + "_state_distribution", p + "_completions_per_minute"));
        }
        if (eco.hasEvents()) {
            sb.append("""

                    # ---- event style: lifecycle rows (evt_*, one per event, latest status) and keyed-state documents (st_*)
                    def _%1$s_events(sm_types):
                        cols = {"EntityId": dht.string, "SmType": dht.string, "Status": dht.string, "Version": dht.int64,
                                "CreatedAtText": dht.string, "UpdatedAtText": dht.string, "EventId": dht.string,
                                "EventType": dht.string, "Domain": dht.string, "Outcome": dht.string, "Error": dht.string,
                                "Attempts": dht.int64, "Retries": dht.int64, "ParentEventId": dht.string, "CausationRoot": dht.string,
                                "Depth": dht.int64, "ProcessorKey": dht.string, "ScheduledAtMs": dht.int64}
                        mapping = {"entityId": "EntityId", "smType": "SmType", "state": "Status", "version": "Version",
                                   "createdAt": "CreatedAtText", "completedAt": "UpdatedAtText", "/model/eventId": "EventId",
                                   "/model/eventType": "EventType", "/model/domain": "Domain", "/model/outcome": "Outcome",
                                   "/model/error": "Error", "/model/attempts": "Attempts", "/model/retries": "Retries",
                                   "/model/parentEventId": "ParentEventId", "/model/causationRoot": "CausationRoot",
                                   "/model/depth": "Depth", "/model/processorKey": "ProcessorKey", "/model/scheduledAt": "ScheduledAtMs"}
                        raw = consume("entity-snapshots", cols, mapping, kc.TableType.append()) \\
                            .where("SmType in " + ", ".join(f"`{t}`" for t in sm_types))
                        latest = raw.agg_by(agg.sorted_last("Version", [c for c in raw.column_names if c != "EntityId"]), by=["EntityId"])
                        return parse_instants(latest, ["CreatedAt", "UpdatedAt"]).update([
                            "ScheduledAt = isNull(ScheduledAtMs) ? null : epochMillisToInstant(ScheduledAtMs)",
                            "AgeMs = isNull(CreatedAt) || isNull(UpdatedAt) ? NULL_LONG : diffMillis(CreatedAt, UpdatedAt)"])


                    """.formatted(p));
            sb.append(p).append("_events_latest = _").append(p).append("_events([")
                    .append(String.join(", ", eco.events().stream().map(e -> "\"" + e.smType() + "\"").toList())).append("])\n");
            sb.append(p).append("_events_by_status = ").append(p).append("_events_latest.count_by(\"Events\", by=[\"Domain\", \"EventType\", \"Status\"])")
                    .append(".sort([\"Domain\", \"EventType\", \"Status\"])\n");
            sb.append(p).append("_event_errors = ").append(p).append("_events_latest.where(\"Status in `ERROR_BLOCKING`, `ERROR_NON_BLOCKING`\")")
                    .append(".sort_descending([\"UpdatedAt\"])\n");
            sb.append(p).append("_events_scheduled = ").append(p).append("_events_latest.where(\"Status == `SCHEDULED`\").sort([\"ScheduledAt\"])\n");
            sb.append(p).append("_causation_depth = ").append(p).append("_events_latest.agg_by([agg.count_(\"Events\"), agg.max_(\"MaxDepth = Depth\"),\n")
                    .append("    agg.min_(\"Started = CreatedAt\"), agg.max_(\"LastUpdate = UpdatedAt\")], by=[\"CausationRoot\"]).sort_descending([\"LastUpdate\"])\n");
            fields.addAll(List.of(p + "_events_latest", p + "_events_by_status", p + "_event_errors", p + "_events_scheduled",
                    p + "_causation_depth"));
            for (EventDecl.StateDecl st : eco.states()) {
                String t = stateTable(st);
                fields.add(t);
                sb.append(t).append(" = _").append(p).append("_root(\"").append(st.smType()).append("\", [\n");
                for (String[] c : deephavenColumns(st.cls())) {
                    sb.append("    (\"").append(c[0]).append("\", \"").append(c[1]).append("\", \"").append(c[2]).append("\"),\n");
                }
                sb.append("])\n");
            }
        }
        sb.append("\nECOSYSTEM_FIELDS = {\n");
        for (String t : fields) {
            sb.append("    \"").append(t).append("\": ").append(t).append(",\n");
        }
        sb.append("}\n");
        return sb.toString();
    }

    /** Deephaven table of a keyed-state type: latest document per key. */
    String stateTable(EventDecl.StateDecl st) {
        return py(eco.name()) + "_" + st.table() + "_latest";
    }

    List<String> deephavenFields() {
        String p = py(eco.name());
        List<String> out = new ArrayList<>(eco.machines().stream().map(this::deephavenTable).toList());
        if (eco.hasMachines()) {
            out.addAll(List.of(p + "_latest", p + "_state_distribution", p + "_completions_per_minute"));
        }
        if (eco.hasEvents()) {
            out.addAll(List.of(p + "_events_latest", p + "_events_by_status", p + "_event_errors", p + "_events_scheduled",
                    p + "_causation_depth"));
            eco.states().forEach(st -> out.add(stateTable(st)));
        }
        return out;
    }

