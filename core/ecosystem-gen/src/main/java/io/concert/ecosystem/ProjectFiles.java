    private static final Set<String> DH_SYSTEM = Set.of("EntityId", "SmType", "State", "Version", "CreatedAt", "CompletedAt",
            "LatencyMs", "CreatedAtText", "CompletedAtText");

    private final Ecosystem eco;
    private final JavaSources java;
    private final ResolvedModel model;

    ProjectFiles(Ecosystem eco, JavaSources java) {
        this.eco = eco;
        this.java = java;
        this.model = eco.model();
    }

    String moduleDir() {
        return "showcases/" + eco.name();
    }

    String envSuffix() {
        return eco.name().toUpperCase(Locale.ROOT).replace('-', '_');
    }

    /**
     * {@code SINK_ROOTS} entries: each machine's root, each event type's lifecycle rows ({@code evt_<type>}: the sinks
     * add the lifecycle columns and flatten the payload class) and each keyed-state type ({@code st_<type>}).
     */
    String sinkRoots() {
        List<String> roots = new ArrayList<>();
        eco.machines().forEach(m -> roots.add(m.smType() + ":" + m.root().qualifiedName()));
        eco.events().forEach(e -> roots.add(e.smType() + ":" + e.cls().qualifiedName()));
        eco.states().forEach(st -> roots.add(st.smType() + ":" + st.cls().qualifiedName()));
        return String.join(",", roots);
    }

