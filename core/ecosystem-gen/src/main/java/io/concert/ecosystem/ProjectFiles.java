    ObjectNode manifest(String modelsDir) {
        JsonNodeFactory f = JsonNodeFactory.instance;
        ObjectNode o = f.objectNode();
        o.put("name", eco.name());
        o.put("package", eco.javaPackage());
        o.put("modelsDir", modelsDir);
        o.put("module", moduleDir());
        if (eco.hasMachines()) {
            o.put("service", eco.name() + "-worker");
        }
        if (eco.hasEvents()) {
            o.put("eventService", eco.name() + "-event-worker");
        }
        o.put("profile", eco.name());
        ArrayNode files = o.putArray("files");
        eco.files().forEach(files::add);
        ArrayNode roots = o.putArray("roots");
        for (MachineDecl m : eco.machines()) {
            ObjectNode r = roots.addObject();
            r.put("smType", m.smType());
            r.put("rootClass", m.root().qualifiedName());
            r.put("table", Ecosystem.rootTable(m.smType()));
            r.put("deephavenTable", deephavenTable(m));
            r.put("initial", m.initial());
            ArrayNode terminal = r.putArray("terminal");
            m.terminal().forEach(terminal::add);
            ArrayNode events = r.putArray("events");
            m.eventTypes().forEach(events::add);
            r.put("sampleKey", Ecosystem.sampleKey(m));
            r.put("happyPath", "samples/flows/" + m.smType() + "-happy-path.json");
        }
        if (eco.hasEvents()) {
            ArrayNode domains = o.putArray("domains");
            eco.domains().forEach(domains::add);
            ArrayNode events = o.putArray("events");
            for (EventDecl e : eco.events()) {
                ObjectNode r = events.addObject();
                r.put("eventType", e.name());
                r.put("domain", e.domain());
                r.put("payloadClass", e.cls().qualifiedName());
                r.put("smType", e.smType());
                r.put("table", e.table());
                ArrayNode locks = r.putArray("locks");
                e.locks().forEach(locks::add);
                r.put("onError", e.onError());
                r.put("maxAttempts", e.maxAttempts());
                ArrayNode emits = r.putArray("emits");
                e.emits().forEach(emits::add);
                r.put("handler", e.handlerClass());
                r.put("sample", "samples/events/" + e.name() + ".json");
            }
            ArrayNode states = o.putArray("states");
            for (EventDecl.StateDecl st : eco.states()) {
                ObjectNode r = states.addObject();
                r.put("name", st.name());
                r.put("stateClass", st.cls().qualifiedName());
                r.put("smType", st.smType());
                r.put("table", st.table());
                if (st.keyTemplate() != null) {
                    r.put("key", st.keyTemplate());
                }
                r.put("deephavenTable", stateTable(st));
            }
            ArrayNode flows = o.putArray("eventFlows");
            new SampleGenerator(eco).rootEvents().forEach(e -> flows.add("samples/event-flows/" + e.name() + "-flow.json"));
        }
        ArrayNode dh = o.putArray("deephavenTables");
        deephavenFields().forEach(dh::add);
        return o;
    }

