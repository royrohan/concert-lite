package io.concert.dashboard;

import io.concert.sdk.MachineCatalog;
import io.concert.sdk.ModelStateMachine;
import io.concert.sdk.StateMachineSpec;
import io.concert.sdk.events.EventCatalog;
import io.concert.sdk.events.EventCatalogs;
import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.lang.reflect.ParameterizedType;
import java.lang.reflect.Type;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Diagrams of the emitted models for {@code GET /api/model/diagrams} (the Model tab's Diagrams and the Diagrams
 * panel concert adds to Legend Studio Lite, which has no diagram renderer of its own). Per state machine:
 *
 * <ul>
 *   <li>{@code stateMermaid}: the states and transitions, each labelled with its event and payload class;
 *   <li>{@code transitionMermaid}: the classes doing the transitions: the entity's data class (the machine's Pure
 *       root) and every payload class, each linked to the root by the events it carries;
 *   <li>{@code modelMermaid}: the machine's whole Pure model (as generated by model-codegen).
 * </ul>
 *
 * Event-style catalogs come with their flow and model diagrams. Everything is derived from the {@link MachineCatalog}
 * and {@link EventCatalog} SPIs, so it is computed once.
 */
final class MachineDiagrams {

    private MachineDiagrams() {
    }

    /** {@code {machines: [...], eventCatalogs: [{name, flowMermaid, modelMermaid}]}}. */
    static Map<String, Object> all() {
        List<Map<String, Object>> machines = new ArrayList<>();
        Set<String> seen = new LinkedHashSet<>();
        for (MachineCatalog c : MachineCatalog.load()) {
            for (MachineCatalog.Machine m : c.machines()) {
                if (seen.add(m.smType())) {
                    machines.add(machine(c.name(), m));
                }
            }
        }
        List<Map<String, Object>> events = new ArrayList<>();
        for (EventCatalog c : EventCatalogs.all().stream().sorted(Comparator.comparing(EventCatalog::name)).toList()) {
            Map<String, Object> e = new LinkedHashMap<>();
            e.put("name", c.name());
            e.put("flowMermaid", c.flowMermaid());
            e.put("modelMermaid", c.modelMermaid());
            e.put("classes", c.events().stream().map(t -> t.payloadType().getName()).distinct().toList());
            events.add(e);
        }
        Map<String, Object> out = new LinkedHashMap<>();
        out.put("machines", machines);
        out.put("eventCatalogs", events);
        return out;
    }

    static Map<String, Object> machine(String catalog, MachineCatalog.Machine m) {
        StateMachineSpec spec = m.spec();
        Class<?> root = dataType(m.impl());
        Map<String, Object> out = new LinkedHashMap<>();
        out.put("smType", m.smType());
        out.put("catalog", catalog);
        out.put("root", root == null ? null : root.getName());
        out.put("initial", spec.initialState());
        out.put("terminal", List.copyOf(spec.terminalStates()));
        out.put("transitions", spec.edges().stream().map(e -> {
            Map<String, Object> t = new LinkedHashMap<>();
            t.put("from", e.from());
            t.put("event", e.eventType());
            t.put("to", e.to());
            t.put("payload", e.payloadType() == null ? null : e.payloadType().getName());
            return t;
        }).toList());
        out.put("classes", classes(root, spec));
        out.put("stateMermaid", stateMermaid(spec));
        out.put("transitionMermaid", transitionMermaid(m.smType(), root, spec, m.modelMermaid()));
        out.put("modelMermaid", m.modelMermaid());
        return out;
    }

    /** The Java classes of the machine's Pure root and payloads, root first (Studio matches its elements to them). */
    private static List<String> classes(Class<?> root, StateMachineSpec spec) {
        Set<String> out = new LinkedHashSet<>();
        if (root != null) {
            out.add(root.getName());
        }
        spec.edges().stream().filter(e -> e.payloadType() != null).forEach(e -> out.add(e.payloadType().getName()));
        return List.copyOf(out);
    }

    /** States and transitions; a typed transition's label names its payload class. */
    static String stateMermaid(StateMachineSpec spec) {
        StringBuilder sb = new StringBuilder("stateDiagram-v2\n");
        sb.append("    [*] --> ").append(spec.initialState()).append('\n');
        for (StateMachineSpec.Edge e : spec.edges()) {
            sb.append("    ").append(e.from()).append(" --> ").append(e.to()).append(" : ").append(e.eventType());
            if (e.payloadType() != null) {
                sb.append(" (").append(e.payloadType().getSimpleName()).append(')');
            }
            sb.append('\n');
        }
        for (String t : spec.terminalStates()) {
            sb.append("    ").append(t).append(" --> [*]\n");
        }
        return sb.toString();
    }

    /**
     * The entity class and its payload classes. Class bodies come from the model diagram when the machine has one
     * (Pure types and multiplicities), else from the classes' fields; each payload points at the root, labelled with
     * the events that carry it.
     */
    static String transitionMermaid(String smType, Class<?> root, StateMachineSpec spec, String modelMermaid) {
        Map<String, String> blocks = classBlocks(modelMermaid);
        String rootId = root == null ? "Entity" : id(root.getSimpleName(), blocks);
        StringBuilder sb = new StringBuilder("classDiagram\n");
        String rootBlock = root == null ? null : blocks.get(rootId);
        sb.append("  class ").append(rootId).append(" {\n    <<").append(smType).append(">>\n");
        if (rootBlock != null) {
            sb.append(rootBlock);
        } else if (root != null) {
            sb.append(fieldLines(root));
        }
        sb.append("    states: ").append(String.join(" · ", spec.states())).append('\n');
        sb.append("  }\n");
        Map<Class<?>, Set<String>> eventsByPayload = new LinkedHashMap<>();
        spec.edges().stream().filter(e -> e.payloadType() != null)
                .forEach(e -> eventsByPayload.computeIfAbsent(e.payloadType(), k -> new LinkedHashSet<>()).add(e.eventType()));
        for (Class<?> p : eventsByPayload.keySet()) {
            String pid = id(p.getSimpleName(), blocks);
            if (pid.equals(rootId)) {
                continue;
            }
            sb.append("  class ").append(pid).append(" {\n");
            String block = blocks.get(pid);
            sb.append(block != null ? block : fieldLines(p));
            sb.append("  }\n");
        }
        eventsByPayload.forEach((p, events) -> {
            String pid = id(p.getSimpleName(), blocks);
            if (!pid.equals(rootId)) {
                sb.append("  ").append(pid).append(" ..> ").append(rootId).append(" : ")
                        .append(String.join(" / ", events)).append('\n');
            }
        });
        return sb.toString();
    }

    /** The data class {@code D} of a {@code ModelStateMachine<D>}, or {@code null} for untyped machines. */
    static Class<?> dataType(Class<?> impl) {
        for (Class<?> c = impl; c != null && c != Object.class; c = c.getSuperclass()) {
            Type t = c.getGenericSuperclass();
            if (t instanceof ParameterizedType pt && pt.getRawType() == ModelStateMachine.class
                    && pt.getActualTypeArguments()[0] instanceof Class<?> d) {
                return d;
            }
        }
        return null;
    }

    /** The member lines of each {@code class X { ... }} block of a Mermaid class diagram, by class id. */
    static Map<String, String> classBlocks(String mermaid) {
        Map<String, String> out = new LinkedHashMap<>();
        if (mermaid == null) {
            return out;
        }
        String id = null;
        StringBuilder body = null;
        for (String line : mermaid.split("\n")) {
            String s = line.strip();
            if (id == null && s.startsWith("class ") && s.endsWith("{")) {
                id = s.substring("class ".length(), s.length() - 1).strip();
                body = new StringBuilder();
            } else if (id != null && s.equals("}")) {
                out.putIfAbsent(id, body.toString());
                id = null;
            } else if (id != null) {
                body.append("    ").append(s).append('\n');
            }
        }
        return out;
    }

    /** The diagram id of a class: its simple name, or the qualified id model-codegen uses when names clash. */
    private static String id(String simpleName, Map<String, String> blocks) {
        if (blocks.containsKey(simpleName)) {
            return simpleName;
        }
        return blocks.keySet().stream().filter(k -> k.endsWith("_" + simpleName)).findFirst().orElse(simpleName);
    }

    private static String fieldLines(Class<?> c) {
        StringBuilder sb = new StringBuilder();
        for (Field f : c.getDeclaredFields()) {
            if (!Modifier.isStatic(f.getModifiers()) && !f.isSynthetic()) {
                sb.append("    +").append(f.getName()).append(" : ").append(f.getType().getSimpleName()).append('\n');
            }
        }
        return sb.toString();
    }
}
